/**
 * Hand-written DXF fixtures.
 *
 * These are authored by hand rather than exported from other CAD software so that each
 * one isolates a specific behaviour and every byte in it is deliberate. They
 * complement — they do not replace — the corpus of real-world drawings, which
 * lives outside the repository because those files are large and frequently
 * covered by client confidentiality.
 */

/** Join group/value pairs into DXF text with CRLF line endings, as other CAD software writes. */
export function dxf(...pairs: Array<[number | string, string | number]>): string {
  return pairs.map(([code, value]) => `${code}\r\n${value}`).join('\r\n') + '\r\n';
}

